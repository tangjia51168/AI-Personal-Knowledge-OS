import { expect, test } from "@playwright/test";

test.use({ trace: "off", screenshot: "off", video: "off" });

test("concept proxy permits only exact bounded revision GET/POST without queries", async ({ page }) => {
  const path = "/api/account/spaces/00000000-0000-0000-0000-000000000001/notes/00000000-0000-0000-0000-000000000002/revisions/00000000-0000-0000-0000-000000000003/concepts";
  expect((await page.request.get(path)).status()).toBe(401);
  expect((await page.request.post(path, { data: {} })).status()).toBe(401);
  expect((await page.request.put(path, { data: {} })).status()).toBe(405);
  expect((await page.request.delete(path)).status()).toBe(405);
  expect((await page.request.get(`${path}?tenant_id=foreign`)).status()).toBe(422);
  expect((await page.request.post(`${path}/extra`, { data: {} })).status()).toBe(404);
  expect((await page.request.post(path, { data: { definition: "x".repeat(16385) } })).status()).toBe(413);
});

test("manual concept definitions use real revision evidence, same-key retry and mobile reconciliation", async ({ page }) => {
  test.setTimeout(120000);
  test.skip(process.env.RUN_ACCOUNT_E2E !== "1", "Explicit isolated account opt-in required");
  const email = process.env.E2E_ANNOTATION_EMAIL;
  const password = process.env.E2E_ANNOTATION_PASSWORD;
  if (!email || !password) throw new Error("Missing isolated concept protocol account");
  let externalPosts = 0;
  page.on("request", request => {
    if (request.method() === "POST" && /\/(summarize|collect)$/.test(new URL(request.url()).pathname)) externalPosts++;
  });
  await page.goto("/account");
  await page.getByLabel("电子邮箱").fill(email);
  await page.getByLabel("密码（12–256 字符）").fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.locator('.account-module-nav a[href="#knowledge"]').click();
  const knowledge = page.getByRole("region", { name: "知识笔记", exact: true });
  await knowledge.getByRole("button", { name: "刷新知识笔记", exact: true }).click();
  await knowledge.getByRole("button", { name: "打开笔记", exact: true }).click();
  const cards = knowledge.getByRole("region", { name: "人工概念卡片", exact: true });
  const status = cards.getByRole("status", { name: "人工概念状态", exact: true });
  const refresh = cards.getByRole("button", { name: "读取本修订概念与证据", exact: true });
  const name = cards.getByLabel("概念名称", { exact: true });
  const definition = cards.getByLabel("人工概念定义", { exact: true });
  const confirm = cards.getByLabel("确认保存人工定义及本修订证据，未经事实核验", { exact: true });
  const versions = knowledge.getByLabel("笔记版本", { exact: true });
  const latest = await versions.inputValue();
  await refresh.click();
  await expect(cards).toContainText("本修订暂无概念卡片。");
  const quote = await cards.getByRole("blockquote", { name: "概念证据原文", exact: true }).textContent();
  expect(quote).toContain("浏览器协议夹具");
  await name.fill("协议概念");
  await definition.fill("人工定义 <script>alert('inert')</script>\n来源未核验");
  await expect(versions).toBeDisabled();
  await confirm.check();
  await definition.fill("人工定义 <script>alert('inert')</script>\n来源未核验。");
  await expect(confirm).not.toBeChecked();
  await confirm.check();
  await page.context().setOffline(true);
  const first = page.waitForRequest(r => r.method() === "POST" && /\/concepts$/.test(new URL(r.url()).pathname));
  await cards.getByRole("button", { name: "保存人工概念", exact: true }).click();
  const original = (await first).postDataJSON();
  await expect(status).toContainText("保存结果可能未知");
  await expect(cards.getByRole("blockquote", { name: "概念证据原文", exact: true })).toHaveCount(0);
  await expect(name).toBeDisabled();
  await page.context().setOffline(false);
  const retry = page.waitForRequest(r => r.method() === "POST" && /\/concepts$/.test(new URL(r.url()).pathname));
  await cards.getByRole("button", { name: "同键重试概念保存", exact: true }).click();
  const retried = await retry;
  expect(retried.postDataJSON()).toEqual(original);
  await expect(status).toContainText("概念已保存");
  await expect(name).toHaveValue("");
  await refresh.click();
  const rows = cards.getByRole("list", { name: "本修订概念卡片", exact: true }).getByRole("listitem");
  await expect(rows).toHaveCount(1);
  await expect(rows).toContainText(original.definition);
  await expect(rows.locator("blockquote")).toHaveText(quote ?? "");
  await expect(rows).toContainText("置信度未评估");
  const authorization = await retried.headerValue("x-knowledge-request");
  if (!authorization) throw new Error("Missing concept authorization");
  expect((await page.request.post(retried.url(), { headers: { "X-Knowledge-Request": authorization }, data: original })).ok()).toBe(true);
  const historical = await versions.locator("option").last().getAttribute("value");
  if (!historical || historical === latest) throw new Error("Missing historical revision");
  await versions.selectOption(historical);
  await cards.getByRole("button", { name: "读取本修订概念与证据", exact: true }).click();
  await expect(cards).toContainText("本修订暂无概念卡片。");
  await versions.selectOption(latest);
  await refresh.click();
  await expect(rows).toHaveCount(1);
  await page.context().setOffline(true);
  await refresh.click();
  await expect(status).toContainText("旧列表与证据已清空");
  await expect(cards.getByRole("list", { name: "本修订概念卡片", exact: true })).toHaveCount(0);
  await page.context().setOffline(false);
  await refresh.click();
  await expect(rows).toHaveCount(1);
  await cards.screenshot({ path: ".cache/module-results/concept-cards-protocol.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await cards.screenshot({ path: ".cache/module-results/concept-cards-mobile-protocol.png" });
  expect(externalPosts).toBe(0);
});
