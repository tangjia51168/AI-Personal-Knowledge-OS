import { expect, test } from "@playwright/test";

test.use({ trace: "off", screenshot: "off", video: "off" });

test("knowledge BFF restricts query names and methods to literal read paths", async ({ page }) => {
  const root = "/api/account/spaces/00000000-0000-0000-0000-000000000001/knowledge";
  expect((await page.request.get(`${root}/search?q=协议`)).status()).toBe(401);
  expect((await page.request.get(`${root}/graph`)).status()).toBe(401);
  for (const kind of ["search", "graph"]) {
    expect((await page.request.post(`${root}/${kind}`)).status()).toBe(405);
    expect((await page.request.put(`${root}/${kind}`)).status()).toBe(405);
    expect((await page.request.get(`${root}/${kind}?user_id=x`)).status()).toBe(422);
    expect((await page.request.get(`${root}/${kind}/extra`)).status()).toBe(404);
  }
  expect((await page.request.get(`${root}/search?q=a&q=b`)).status()).toBe(422);
  expect((await page.request.get(`${root}/graph?limit=999`)).status()).toBe(422);
});

test("saved content search opens the matched revision and real evidence then navigates space links", async ({ page }) => {
  test.setTimeout(120000);
  test.skip(process.env.RUN_ACCOUNT_E2E !== "1", "Explicit isolated account opt-in required");
  const email = process.env.E2E_EXPLORER_EMAIL, password = process.env.E2E_EXPLORER_PASSWORD;
  if (!email || !password) throw new Error("Missing isolated explorer fixtures");
  let externalPosts = 0;
  page.on("request", request => { if (request.method() === "POST" && /\/(summarize|collect)$/.test(new URL(request.url()).pathname)) externalPosts++; });
  await page.goto("/account#knowledge");
  await page.getByLabel("电子邮箱", { exact: true }).fill(email);
  await page.getByLabel("密码（12–256 字符）", { exact: true }).fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  const knowledge = page.getByRole("region", { name: "知识笔记", exact: true });
  const explorer = page.getByRole("region", { name: "知识组织与检索工作区", exact: true });
  const status = explorer.getByRole("status", { name: "知识检索状态", exact: true });
  const captured = page.waitForRequest(request => request.method() === "GET" && /\/notes$/.test(new URL(request.url()).pathname));
  await knowledge.getByRole("button", { name: "刷新知识笔记", exact: true }).click();
  const request = await captured, auth = await request.headerValue("x-knowledge-request");
  if (!auth) throw new Error("Missing authenticated fixture request");
  const root = new URL(request.url()).pathname.replace(/\/notes$/, "");
  const headers = { "X-Knowledge-Request": auth };
  const response = await page.request.get(`${root}/notes`, { headers });
  const notes = (await response.json()).data;
  expect(notes).toHaveLength(2);
  const first = (await (await page.request.get(`${root}/notes/${notes[0].id}`, { headers })).json()).data.revision;
  const link = await page.request.put(`${root}/notes/${notes[0].id}/links/${notes[1].id}`, { headers });
  expect(link.status()).toBe(200);
  const annotation = await page.request.post(`${root}/notes/${notes[0].id}/revisions/${first.id}/annotations`, {
    headers, data: { idempotency_key: crypto.randomUUID(), kind: "overview", item_index: 0, expected_quote: first.document.overview.text, body: "检索专项批注 %_!\\ 😀（协议夹具）" },
  });
  expect(annotation.status()).toBe(200);
  await explorer.getByLabel("检索关键词", { exact: true }).fill("%_!\\");
  await explorer.getByLabel("检索内容范围", { exact: true }).selectOption("annotation");
  await explorer.getByRole("button", { name: "搜索知识内容", exact: true }).click();
  const hits = explorer.getByRole("list", { name: "知识检索结果", exact: true }).locator(":scope > li");
  await expect(hits).toHaveCount(1);
  await expect(hits).toContainText("检索专项批注");
  await explorer.getByRole("button", { name: "打开命中修订", exact: true }).click();
  const fixed = explorer.getByRole("region", { name: "检索固定修订", exact: true });
  await expect(fixed.getByRole("heading", { level: 4 })).toContainText(first.title);
  await fixed.getByRole("button", { name: "加载原文证据", exact: true }).click();
  await expect(fixed.getByRole("status", { name: "原文证据状态", exact: true })).toContainText("已加载当前修订的真实证据");
  await explorer.getByLabel("检索内容范围", { exact: true }).selectOption("evidence");
  await explorer.getByLabel("检索关键词", { exact: true }).fill("浏览器协议夹具");
  await explorer.getByRole("button", { name: "搜索知识内容", exact: true }).click();
  await expect(hits).toHaveCount(2);
  await expect(hits.first()).toContainText("原文证据");
  await explorer.getByRole("button", { name: "读取空间人工关系图", exact: true }).click();
  await expect(status).toContainText("2 个节点、1 条人工链接");
  const drawing = explorer.getByRole("img", { name: "空间人工关系示意", exact: true });
  const viewStatus = explorer.getByRole("status", { name: "空间图视图状态", exact: true });
  await expect(drawing).toBeVisible();
  await explorer.getByLabel("图中标题搜索", { exact: true }).fill("检索甲");
  await expect(viewStatus).toContainText("显示 1 / 2 个已读取节点、0 / 1 条");
  await explorer.getByLabel("图中标题搜索", { exact: true }).fill("不存在的节点");
  await expect(explorer.getByRole("list", { name: "空间图笔记", exact: true }).getByRole("listitem")).toHaveCount(0);
  await explorer.getByLabel("图中标题搜索", { exact: true }).fill("");
  await explorer.getByLabel("图中连接筛选", { exact: true }).selectOption("isolated");
  await expect(viewStatus).toContainText("显示 0 / 2");
  await explorer.getByLabel("图中连接筛选", { exact: true }).selectOption("linked");
  await expect(viewStatus).toContainText("显示 2 / 2");
  await explorer.getByRole("button", { name: "放大图谱", exact: true }).click();
  await expect(viewStatus).toContainText("缩放 125%");
  const geometry = drawing.locator(":scope > g");
  const initialTransform = await geometry.getAttribute("transform");
  await drawing.focus();
  await drawing.press("ArrowRight");
  await expect(geometry).not.toHaveAttribute("transform", initialTransform!);
  await drawing.scrollIntoViewIfNeeded();
  const bounds = await drawing.boundingBox();
  if (!bounds) throw new Error("Missing graph geometry");
  const beforeDrag = await geometry.getAttribute("transform");
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width / 2 + 45, bounds.y + bounds.height / 2 + 30, { steps: 4 });
  await page.mouse.up();
  await expect(geometry).not.toHaveAttribute("transform", beforeDrag!);
  await explorer.getByRole("button", { name: "重置图谱视图", exact: true }).click();
  await expect(viewStatus).toContainText("缩放 100%");
  await expect(geometry).toHaveAttribute("transform", "translate(300 300) scale(1) translate(-300 -300)");
  await explorer.getByRole("button", { name: "打开图中修订", exact: true }).first().click();
  await expect(fixed).toBeVisible();
  await explorer.screenshot({ path: ".cache/module-results/organization-track-protocol.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await explorer.screenshot({ path: ".cache/module-results/organization-track-mobile-protocol.png" });
  await page.context().setOffline(true);
  await explorer.getByRole("button", { name: "搜索知识内容", exact: true }).click();
  await expect(status).toContainText("已清空旧结果");
  await expect(hits).toHaveCount(0);
  await expect(fixed).toHaveCount(0);
  await expect(explorer.getByRole("img")).toHaveCount(0);
  await page.context().setOffline(false);
  await explorer.getByRole("button", { name: "搜索知识内容", exact: true }).click();
  await expect(hits).toHaveCount(2);
  await explorer.getByLabel("检索关键词", { exact: true }).fill("当前条件不存在的文字");
  await expect(hits).toHaveCount(0);
  await explorer.getByRole("button", { name: "搜索知识内容", exact: true }).click();
  await expect(explorer).toContainText("当前条件没有命中已保存内容");
  expect(externalPosts).toBe(0);
});
