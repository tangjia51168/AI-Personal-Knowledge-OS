import {expect, test} from "@playwright/test";
test.use({trace:"off",screenshot:"off",video:"off"});
test("collection BFF methods and query boundaries", async ({page}) => {
  const base = "/api/account/spaces/00000000-0000-0000-0000-000000000001/collections";
  expect((await page.request.get(base)).status()).toBe(401);
  expect((await page.request.put(base)).status()).toBe(405);
  expect((await page.request.get(base + "?tenant=x")).status()).toBe(422);
  expect((await page.request.post(base + "/00000000-0000-0000-0000-000000000002/items")).status()).toBe(405);
});
test("real collection creation, source membership, ordering, archive and error clearing", async ({page}) => {
  test.skip(process.env.RUN_ACCOUNT_E2E !== "1", "Explicit isolated fixture required");
  await page.goto("/account#collections");
  await page.getByLabel("电子邮箱",{exact:true}).fill(process.env.E2E_EXPLORER_EMAIL!);
  await page.getByLabel("密码（12–256 字符）",{exact:true}).fill(process.env.E2E_EXPLORER_PASSWORD!);
  await page.getByRole("button",{name:"登录",exact:true}).click();
  const center=page.getByRole("region",{name:"收藏与合集",exact:true});
  await center.getByRole("button",{name:"读取收藏与合集",exact:true}).click();
  await center.getByRole("combobox",{name:"分组类型",exact:true}).selectOption("collection");
  await center.getByLabel("分组名称",{exact:true}).fill("浏览器课程合集");
  await center.getByRole("button",{name:"创建分组",exact:true}).click();
  await expect(center.getByRole("status",{name:"收藏状态",exact:true})).toContainText("已创建");
  await center.getByRole("button",{name:/浏览器课程合集/}).click();
  const read=await page.request.get("/api/account/spaces");
  const space=(await read.json()).data.find((row:{role:string})=>row.role==="owner").id;
  const sources=await page.request.get(`/api/account/spaces/${space}/sources?status=accepted&limit=20`);
  const id=(await sources.json()).data[0].id;
  await center.getByLabel("已有素材编号",{exact:true}).fill(id);
  await center.getByLabel("排列位置（0–199）",{exact:true}).fill("5");
  await center.getByRole("button",{name:"加入当前组",exact:true}).click();
  await expect(center.locator(".collection-items li")).toHaveCount(1);
  await center.getByRole("button",{name:"前移",exact:true}).click();
  await expect(center.locator(".collection-order")).toHaveText("4");
  await page.reload();
  await center.getByRole("button",{name:"读取收藏与合集",exact:true}).click();
  await center.getByRole("button",{name:/浏览器课程合集/}).click();
  await expect(center.locator(".collection-order")).toHaveText("4");
  await center.getByRole("button",{name:"归档分组",exact:true}).click();
  await center.getByRole("button",{name:/浏览器课程合集/}).click();
  await expect(center.getByRole("button",{name:"恢复分组",exact:true})).toBeVisible();
  await expect(center.getByLabel("已有素材编号",{exact:true})).toHaveCount(0);
  await center.getByRole("button",{name:"移出",exact:true}).click();
  await expect(center.locator(".collection-items li")).toHaveCount(0);
  await center.getByRole("button",{name:"恢复分组",exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await center.screenshot({path:".cache/module-results/collections-mobile.png"});
  await page.route("**/collections",route=>route.abort());
  await center.getByRole("button",{name:"读取收藏与合集",exact:true}).click();
  await expect(center.getByRole("status",{name:"收藏状态",exact:true})).toContainText("旧结果已清空");
  await expect(center.locator(".collection-card")).toHaveCount(0);
});
