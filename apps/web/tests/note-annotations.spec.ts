import { expect, test } from "@playwright/test";

test.use({ trace: "off", screenshot: "off", video: "off" });

test("annotation proxy bounds the exact revision path and body", async ({ page }) => {
  const path = "/api/account/spaces/00000000-0000-0000-0000-000000000001/notes/00000000-0000-0000-0000-000000000002/revisions/00000000-0000-0000-0000-000000000003/annotations";
  expect((await page.request.get(path)).status()).toBe(401);
  expect((await page.request.post(path, { data: {} })).status()).toBe(401);
  expect((await page.request.put(path, { data: {} })).status()).toBe(405);
  expect((await page.request.delete(path)).status()).toBe(405);
  expect((await page.request.post(`${path}/extra`, { data: {} })).status()).toBe(404);
  expect((await page.request.post(path, { data: { body: "x".repeat(16385) } })).status()).toBe(413);
});

test("manual annotations preserve quotes and revisions with draft protection and same-key retry", async ({ page }) => {
  test.setTimeout(90000);
  test.skip(process.env.RUN_ACCOUNT_E2E !== "1", "Explicit isolated account opt-in required");
  const email = process.env.E2E_ANNOTATION_EMAIL;
  const password = process.env.E2E_ANNOTATION_PASSWORD;
  if (!email || !password) throw new Error("Missing isolated annotation protocol account");
  let externalPosts = 0;
  page.on("request", request => {
    if (request.method() === "POST" && /\/(summarize|collect)$/.test(new URL(request.url()).pathname)) externalPosts++;
  });
  await page.goto("/account");
  await page.getByLabel("电子邮箱").fill(email);
  await page.getByLabel("密码（12–256 字符）").fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.locator('.account-module-nav a[href="#knowledge"]').click();
  const knowledge = page.getByRole("region", { name: "知识笔记", exact: true });
  await knowledge.getByRole("button", { name: "刷新知识笔记", exact: true }).click();
  await knowledge.getByRole("button", { name: "打开笔记", exact: true }).click();
  const annotations = knowledge.getByRole("region", { name: "逐段人工批注", exact: true });
  const status = annotations.getByRole("status", { name: "笔记批注状态", exact: true });
  const draft = annotations.getByLabel("人工批注内容", { exact: true });
  const versions = knowledge.getByLabel("笔记版本", { exact: true });
  const latest = await versions.inputValue();
  const originalMarkdown = await knowledge.getByRole("region", { name: "笔记内容", exact: true }).locator("pre").textContent();
  const quote = await annotations.getByRole("blockquote", { name: "批注原段", exact: true }).textContent();
  await annotations.getByRole("button", { name: "刷新当前版本批注", exact: true }).click();
  await expect(annotations).toContainText("当前修订暂无批注。");
  await draft.fill("临时草稿");
  await expect(versions).toBeDisabled();
  await expect(knowledge.getByRole("button", { name: "开始人工修订", exact: true })).toBeDisabled();
  await expect(knowledge.getByRole("button", { name: "应用笔记筛选", exact: true })).toBeDisabled();
  await annotations.getByRole("button", { name: "放弃批注草稿", exact: true }).click();
  await expect(draft).toHaveValue("");
  await expect(versions).toBeEnabled();
  const body = "人工批注协议 <script>alert('text')</script>\n未调用模型。";
  await draft.fill(body);
  await expect(draft).toHaveValue(body);
  await expect(annotations.getByRole("button", { name: "保存人工批注", exact: true })).toBeEnabled();
  await page.context().setOffline(true);
  const failed = page.waitForRequest(request => request.method() === "POST" && /\/annotations$/.test(new URL(request.url()).pathname));
  await annotations.getByRole("button", { name: "保存人工批注", exact: true }).click();
  const first = await failed;
  await expect(status).toContainText("重试使用原内容与幂等键");
  await expect(draft).toBeDisabled();
  await expect(versions).toBeDisabled();
  await page.context().setOffline(false);
  const retried = page.waitForRequest(request => request.method() === "POST" && /\/annotations$/.test(new URL(request.url()).pathname));
  await annotations.getByRole("button", { name: "以原键重试批注", exact: true }).click();
  const second = await retried;
  expect(second.postDataJSON()).toEqual(first.postDataJSON());
  await expect(status).toContainText("人工批注已保存到当前修订");
  const rows = annotations.getByRole("list", { name: "当前版本批注", exact: true }).getByRole("listitem");
  await expect(rows).toHaveCount(1);
  await expect(rows.locator("pre")).toHaveText(body);
  await expect(rows.locator("blockquote")).toHaveText(quote ?? "");
  await expect(draft).toHaveValue("");
  const authorization = await second.headerValue("x-knowledge-request");
  if (!authorization) throw new Error("Missing annotation authorization");
  const headers = { "X-Knowledge-Request": authorization };
  expect((await page.request.post(second.url(), { headers, data: second.postDataJSON() })).ok()).toBe(true);
  const list = await page.request.get(`${second.url()}?limit=1&cursor=invalid`, { headers });
  expect(list.status()).toBe(422);
  const historical = await versions.locator("option").last().getAttribute("value");
  if (!historical || historical === latest) throw new Error("Missing historical revision");
  await versions.selectOption(historical);
  await annotations.getByRole("button", { name: "刷新当前版本批注", exact: true }).click();
  await expect(annotations).toContainText("当前修订暂无批注。");
  await versions.selectOption(latest);
  await annotations.getByRole("button", { name: "刷新当前版本批注", exact: true }).click();
  await expect(rows).toHaveCount(1);
  await expect(knowledge.getByRole("region", { name: "笔记内容", exact: true }).locator("pre")).toHaveText(originalMarkdown ?? "");
  await page.locator('.account-module-nav a[href="#audit"]').click();
  const audit = page.getByRole("region", { name: "空间审计记录", exact: true });
  await audit.getByRole("button", { name: "刷新审计记录", exact: true }).click();
  await expect(audit.getByRole("listitem").filter({ hasText: "追加逐段人工批注" })).toHaveCount(1);
  expect(externalPosts).toBe(0);
});
