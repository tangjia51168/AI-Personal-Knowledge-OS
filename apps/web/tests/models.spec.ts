import { expect, test } from "@playwright/test";

test.use({ trace: "off", screenshot: "off", video: "off" });

test("real encrypted model settings and per-account preferences persist without inference", async ({ page }) => {
  test.skip(process.env.RUN_ACCOUNT_E2E !== "1", "Explicit isolated account opt-in required");
  const email = process.env.E2E_ACCOUNT_EMAIL;
  const password = process.env.E2E_ACCOUNT_PASSWORD;
  if (!email || !password) throw new Error("Missing isolated credentials");
  await page.goto("/account");
  await page.getByLabel("电子邮箱").fill(email);
  await page.getByLabel("密码（12–256 字符）").fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.locator('.account-module-nav a[href="#models"]').click();
  const settings = page.getByRole("region", { name: "模型与隐私设置" });
  await settings.getByRole("button", { name: "加载模型设置" }).click();
  await settings.getByLabel("模型名称").fill("browser-unverified-model");
  const dummy = "browser-test-only-never-used-key";
  await settings.getByLabel("供应商密钥").fill(dummy);
  await settings.getByRole("button", { name: "保存模型配置" }).click();
  await expect(settings.getByRole("status")).toHaveText("配置已保存，密钥不会回显。");
  await expect(settings.getByLabel("供应商密钥")).toHaveValue("");
  await expect(settings).toContainText("browser-unverified-model · 禁用 · 已加密密钥");
  expect(await settings.textContent()).not.toContain(dummy);
  await settings.getByLabel("主题偏好").selectOption("dark");
  await settings.getByRole("button", { name: "保存账户偏好" }).click();
  await expect(settings.getByRole("status")).toContainText("偏好已保存");
  await settings.getByLabel("主题偏好").selectOption("light");
  await settings.getByRole("button", { name: "加载模型设置" }).click();
  await expect(settings.getByLabel("主题偏好")).toHaveValue("dark");
  await settings.getByRole("button", { name: "重新加密" }).click();
  await expect(settings.getByRole("status")).toContainText("重新加密");
  await settings.getByRole("button", { name: "编辑配置", exact: true }).click();
  await expect(settings.getByRole("combobox", { name: /^供应商/ })).toBeDisabled();
  await expect(settings.getByLabel("供应商密钥")).toHaveValue("");
  await settings.getByLabel("模型名称").fill("browser-updated-model");
  await settings.getByLabel("调用优先级").fill("7");
  await settings.getByRole("button", { name: "保存配置修改" }).click();
  await expect(settings.getByRole("status")).toHaveText("配置已保存，密钥不会回显。");
  await expect(settings).toContainText("browser-updated-model · 禁用 · 已加密密钥");
  await settings.getByRole("button", { name: "编辑配置", exact: true }).click();
  await expect(settings.getByLabel("调用优先级")).toHaveValue("7");
  const replacement = "browser-replacement-never-used-key";
  await settings.getByLabel("供应商密钥").fill(replacement);
  await settings.getByRole("button", { name: "保存配置修改" }).click();
  await expect(settings.getByRole("status")).toHaveText("配置已保存，密钥不会回显。");
  await expect(settings.getByLabel("供应商密钥")).toHaveValue("");
  expect(await settings.textContent()).not.toContain(replacement);
  await settings.getByRole("button", { name: "禁用并清除密钥" }).click();
  await expect(settings).toContainText("browser-updated-model · 禁用 · 无密钥");
  await settings.getByRole("button", { name: "编辑配置", exact: true }).click();
  await expect(settings.getByLabel("供应商密钥")).toHaveValue("");
  await settings.getByRole("button", { name: "取消编辑" }).click();
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain(dummy);
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain(replacement);
});
