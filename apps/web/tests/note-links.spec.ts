  const email = process.env.E2E_NOTE_LINK_EMAIL;
  const password = process.env.E2E_NOTE_LINK_PASSWORD;
  if (!email || !password) throw new Error("Missing isolated note-link protocol fixtures");
  let paidPosts = 0;
  let collectionPosts = 0;
  page.on("request", request => {
    if (request.method() !== "POST") return;
    if (/\/summarize$/.test(new URL(request.url()).pathname)) paidPosts++;
    if (/\/collect$/.test(new URL(request.url()).pathname)) collectionPosts++;
  });
  await page.goto("/account#knowledge");
  await expect(page).toHaveURL(/\/account#knowledge$/);
  await expect(page.getByRole("region", { name: "邮箱验证与找回密码" })).not.toContainText("链接无效");
  await page.getByLabel("电子邮箱").fill(email);
  await page.getByLabel("密码（12–256 字符）").fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  const knowledge = page.getByRole("region", { name: "知识笔记", exact: true });
  await expect(page.locator("#knowledge h2")).toBeInViewport();
