import { expect, test } from "@playwright/test";

test.use({ trace: "off", screenshot: "off", video: "off" });

test("note-link proxy restricts exact read and write paths and methods", async ({ page }) => {
  const root = "/api/account/spaces/00000000-0000-0000-0000-000000000001";
  const note = `${root}/notes/00000000-0000-0000-0000-000000000002`;
  const links = `${note}/links`;
  const target = `${links}/00000000-0000-0000-0000-000000000003`;
  expect((await page.request.get(links)).status()).toBe(401);
  expect((await page.request.post(links, { data: {} })).status()).toBe(405);
  expect((await page.request.put(links, { data: {} })).status()).toBe(405);
  expect((await page.request.delete(links)).status()).toBe(405);
  expect((await page.request.get(target)).status()).toBe(405);
  expect((await page.request.post(target, { data: {} })).status()).toBe(405);
  expect((await page.request.put(target)).status()).toBe(401);
  expect((await page.request.delete(target)).status()).toBe(401);
  expect((await page.request.put(`${target}/extra`)).status()).toBe(404);
  expect((await page.request.put(target, { data: { value: "x".repeat(4096) } })).status()).toBe(413);
});

