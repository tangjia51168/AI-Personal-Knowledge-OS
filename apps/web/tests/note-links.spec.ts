  await knowledge.getByRole("button", { name: "刷新知识笔记", exact: true }).click();
  const listRequest = await listed;
  const authorization = await listRequest.headerValue("x-knowledge-request");
  if (!authorization) throw new Error("Missing authenticated note-link request");
  const headers = { "X-Knowledge-Request": authorization };
  const notes = knowledge.getByRole("list", { name: "笔记结果", exact: true }).locator(":scope > li");
  await expect(notes).toHaveCount(2);
  await notes.filter({ hasText: "浏览器协议笔记乙版本2" }).getByRole("button", { name: "打开笔记" }).click();
  let links = knowledge.getByRole("region", { name: "笔记双向链接", exact: true });
  let status = links.getByRole("status", { name: "笔记链接状态", exact: true });
  await expect(status).toHaveText("已加载双向人工链接。");
  await expect(links).toContainText("本笔记尚未建立人工链接。");
  await links.getByLabel("关联笔记关键词", { exact: true }).fill("笔记甲");
  await links.getByRole("button", { name: "搜索可关联笔记", exact: true }).click();
  await expect(status).toContainText("找到 1 篇可关联笔记");
  const target = links.getByLabel("可关联笔记", { exact: true });
  await target.selectOption({ index: 1 });
  await page.context().setOffline(true);
  const interrupted = page.waitForRequest(request => request.method() === "PUT" && /\/links\/[0-9a-f-]+$/.test(new URL(request.url()).pathname));
  await links.getByRole("button", { name: "建立双向链接", exact: true }).click();
  const failedPath = new URL((await interrupted).url()).pathname;
  await expect(status).toContainText("可刷新链接核对结果");
  await expect(target).not.toHaveValue("");
  await page.context().setOffline(false);
  const submitted = page.waitForRequest(request => request.method() === "PUT" && /\/links\/[0-9a-f-]+$/.test(new URL(request.url()).pathname));
  await links.getByRole("button", { name: "建立双向链接", exact: true }).click();
  const request = await submitted;
  expect(new URL(request.url()).pathname).toBe(failedPath);
  await expect(status).toHaveText("已建立双向人工链接。");
  const linked = links.getByRole("list", { name: "已链接笔记", exact: true }).getByRole("listitem");
  await expect(linked).toHaveCount(1);
  await expect(linked).toContainText("浏览器协议笔记甲版本2（无模型调用） · 最新版本 2 · 人工链接");
  expect((await page.request.put(request.url(), { headers })).ok()).toBe(true);

  const match = failedPath.match(/^(.*\/notes\/)([0-9a-f-]+)\/links\/([0-9a-f-]+)$/);
  if (!match) throw new Error("Unexpected note-link path");
  const root = match[1];
  const leftId = match[2];
  const rightId = match[3];
  let graph = links.getByRole("region", { name: "人工链接局部图谱", exact: true });
  await graph.getByRole("button", { name: "读取局部图谱", exact: true }).click();
  await expect(graph.getByRole("status")).toHaveText("已加载 2 个节点、1 条人工链接。");
  await expect(graph.getByRole("img", { name: "人工链接局部图谱示意" })).toBeVisible();
  await expect(graph.getByRole("list", { name: "图谱笔记节点" }).getByRole("listitem")).toHaveCount(2);
  await expect(graph).toContainText("不表示支持、反驳、因果");
  // Only the explicitly identified protocol graph region, no form/password/token.
  await graph.screenshot({ path: ".cache/module-results/manual-note-graph-protocol.png" });
  await graph.getByLabel("图谱范围", { exact: true }).selectOption("2");
  await expect(graph.getByRole("img")).toHaveCount(0);
  await page.context().setOffline(true);
  await graph.getByRole("button", { name: "读取局部图谱", exact: true }).click();
  await expect(graph.getByRole("status")).toContainText("未展示旧图，可手动重试");
  await expect(graph.getByRole("img")).toHaveCount(0);
  await page.context().setOffline(false);
  const graphRead = page.waitForRequest(request => /\/graph\?depth=2$/.test(request.url()));
  await graph.getByRole("button", { name: "读取局部图谱", exact: true }).click();
  await graphRead;
  await expect(graph.getByRole("status")).toHaveText("已加载 2 个节点、1 条人工链接。");
  await graph.getByRole("button", { name: /从图谱打开笔记：.*笔记甲/ }).click();
  await expect(knowledge.getByRole("status", { name: "笔记列表状态" })).toHaveText("已从双向链接打开关联笔记。");
  await expect(knowledge.getByRole("region", { name: "笔记内容" })).toContainText("浏览器协议笔记甲版本2");
  links = knowledge.getByRole("region", { name: "笔记双向链接", exact: true });
  status = links.getByRole("status", { name: "笔记链接状态", exact: true });
  await expect(status).toHaveText("已加载双向人工链接。");
  await expect(links.getByRole("list", { name: "已链接笔记" })).toContainText("浏览器协议笔记乙版本2");

  graph = links.getByRole("region", { name: "人工链接局部图谱", exact: true });
  await graph.getByRole("button", { name: "读取局部图谱", exact: true }).click();
  await expect(graph.getByRole("status")).toHaveText("已加载 2 个节点、1 条人工链接。");

  const versions = knowledge.getByLabel("笔记版本", { exact: true });
  const latest = await versions.inputValue();
  const historical = await versions.locator("option").last().getAttribute("value");
  if (!historical || historical === latest) throw new Error("Missing historical note-link revision");
  await versions.selectOption(historical);
  await expect(links.getByRole("list", { name: "已链接笔记" })).toContainText("浏览器协议笔记乙版本2");
  await knowledge.getByRole("button", { name: "打开最新版本", exact: true }).click();
  await knowledge.getByRole("button", { name: "开始人工修订", exact: true }).click();
  const editor = knowledge.getByRole("region", { name: "笔记人工修订", exact: true });
  await expect(graph.getByRole("button", { name: "读取局部图谱", exact: true })).toBeDisabled();
  await expect(graph.getByRole("button", { name: /从图谱打开笔记：.*笔记乙/ })).toBeDisabled();
  await editor.getByLabel("修订标题", { exact: true }).fill("链接保留人工修订（无模型调用）");
  await editor.getByRole("button", { name: "保存为新版本", exact: true }).click();
  await expect(editor).not.toBeVisible();
  await expect(links.getByRole("list", { name: "已链接笔记" })).toContainText("浏览器协议笔记乙版本2");

  await links.getByRole("button", { name: /移除关联笔记/ }).click();
  await expect(status).toContainText("已移除双向人工链接");
  await expect(links).toContainText("本笔记尚未建立人工链接。");
  await expect(graph.getByRole("img")).toHaveCount(0);
  await graph.getByRole("button", { name: "读取局部图谱", exact: true }).click();
  await expect(graph.getByRole("status")).toHaveText("已加载 1 个节点、0 条人工链接。");
  await expect(graph).toContainText("当前范围没有有效人工链接，仅展示中心笔记。");
  for (const noteId of [leftId, rightId]) {
    const response = await page.request.get(`${root}${noteId}/links`, { headers });
    expect(response.ok()).toBe(true);
    expect((await response.json()).data).toEqual([]);
  }
  await page.locator('.account-module-nav a[href="#audit"]').click();
  const audit = page.getByRole("region", { name: "空间审计记录", exact: true });
  await audit.getByRole("button", { name: "刷新审计记录", exact: true }).click();
