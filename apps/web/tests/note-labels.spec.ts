import { expect, test } from "@playwright/test";

test.use({ trace: "off", screenshot: "off", video: "off" });

test("classification proxy restricts exact paths, methods and bounded bodies", async ({ page }) => {
  const root = "/api/account/spaces/00000000-0000-0000-0000-000000000001";
  const note = `${root}/notes/00000000-0000-0000-0000-000000000002`;
  const link = `${note}/labels/00000000-0000-0000-0000-000000000003`;
  expect((await page.request.get(`${root}/labels`)).status()).toBe(401);
  expect((await page.request.delete(`${root}/labels`)).status()).toBe(405);
  expect((await page.request.put(`${root}/labels`, { data: {} })).status()).toBe(405);
  expect((await page.request.post(`${root}/labels/extra`, { data: {} })).status()).toBe(404);
  expect((await page.request.post(`${note}/labels`, { data: {} })).status()).toBe(405);
  expect((await page.request.get(link)).status()).toBe(405);
  expect((await page.request.post(link, { data: {} })).status()).toBe(405);
  expect((await page.request.put(link)).status()).toBe(401);
  expect((await page.request.delete(`${link}/extra`)).status()).toBe(404);
  expect((await page.request.post(`${root}/labels`, { data: { kind: "topic", name: "x".repeat(4096) } })).status()).toBe(413);
  const directory = `${root}/labels/manage`;
  const definition = `${root}/labels/00000000-0000-0000-0000-000000000003`;
  expect((await page.request.get(directory)).status()).toBe(401);
  expect((await page.request.post(directory)).status()).toBe(405);
  expect((await page.request.get(`${directory}?unknown=1`)).status()).toBe(422);
  expect((await page.request.patch(definition, { data: { active: false, expected_version: 1 } })).status()).toBe(401);
  expect((await page.request.get(definition)).status()).toBe(405);
  expect((await page.request.patch(`${definition}/extra`)).status()).toBe(404);
  expect((await page.request.patch(`${root}/labels`)).status()).toBe(405);
  expect((await page.request.patch(definition, { data: { name: "x".repeat(17000), expected_version: 1 } })).status()).toBe(413);
});

test("human topics and tags persist across revisions and filter real note lists without AI", async ({ page }) => {
  test.setTimeout(120000);
  test.skip(process.env.RUN_ACCOUNT_E2E !== "1", "Explicit isolated account opt-in required");
  const email = process.env.E2E_LABEL_EMAIL;
  const password = process.env.E2E_LABEL_PASSWORD;
  const fixtureNote = process.env.E2E_LABEL_NOTE_ID;
  if (!email || !password || !fixtureNote) throw new Error("Missing isolated manual label protocol fixtures");
  let paidPosts = 0;
  let collectionPosts = 0;
  page.on("request", request => {
    if (request.method() !== "POST") return;
    if (/\/summarize$/.test(new URL(request.url()).pathname)) paidPosts++;
    if (/\/collect$/.test(new URL(request.url()).pathname)) collectionPosts++;
  });
  await page.goto("/account");
  await page.getByLabel("电子邮箱").fill(email);
  await page.getByLabel("密码（12–256 字符）").fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.locator('.account-module-nav a[href="#knowledge"]').click();
  const knowledge = page.getByRole("region", { name: "知识笔记", exact: true });
  const notes = knowledge.getByRole("list", { name: "笔记结果", exact: true }).locator(":scope > li");
  const listed = page.waitForRequest(request => request.method() === "GET" && /\/notes$/.test(new URL(request.url()).pathname));
  await knowledge.getByRole("button", { name: "刷新知识笔记", exact: true }).click();
  const listRequest = await listed;
  const authorization = await listRequest.headerValue("x-knowledge-request");
  if (!authorization) throw new Error("Missing authenticated classification list request");
  const root = new URL(listRequest.url()).pathname.replace(/\/notes$/, "");
  const headers = { "X-Knowledge-Request": authorization };
  await expect(notes).toHaveCount(1);
  await knowledge.getByRole("button", { name: "打开笔记", exact: true }).click();
  const classification = knowledge.getByRole("region", { name: "笔记人工分类", exact: true });
  const assigned = classification.getByRole("list", { name: "已关联分类", exact: true }).locator(":scope > li");
  const status = classification.getByRole("status", { name: "笔记分类状态", exact: true });
  const content = knowledge.getByRole("region", { name: "笔记内容", exact: true });
  const versions = knowledge.getByLabel("笔记版本", { exact: true });
  await expect(status).toHaveText("已加载真实笔记分类。");
  await expect(assigned).toHaveCount(0);
  const latestRevision = await versions.inputValue();
  const beforeVersions = await versions.locator("option").count();
  const beforeMarkdown = await content.locator("pre").textContent();
  const name = classification.getByLabel("新分类名称", { exact: true });
  const kind = classification.getByLabel("新分类类型", { exact: true });
  const create = classification.getByRole("button", { name: "创建分类", exact: true });
  const attach = classification.getByRole("button", { name: "关联到笔记", exact: true });

  await name.fill("a".repeat(61));
  await create.click();
  await expect(status).toContainText("1–60 字符");
  await expect(name).toHaveValue("a".repeat(61));
  await name.fill("  Ｓｉｍｕｌｉｎｋ  ");
  await create.click();
  await expect(status).toContainText("分类已保存到空间");
  const topic = await classification.getByLabel("已有主题或标签", { exact: true }).inputValue();
  expect(topic).toBeTruthy();
  await expect(name).toHaveValue("");
  // A failed transport keeps the same association target available for retry.
  await page.context().setOffline(true);
  const failedAttach = page.waitForRequest(request => request.method() === "PUT" && /\/labels\/[0-9a-f-]+$/.test(new URL(request.url()).pathname));
  await attach.click();
  const failedPath = new URL((await failedAttach).url()).pathname;
  await expect(status).toContainText("可刷新分类核对结果");
  await expect(classification.getByLabel("已有主题或标签", { exact: true })).toHaveValue(topic);
  await page.context().setOffline(false);
  const retriedAttach = page.waitForRequest(request => request.method() === "PUT" && /\/labels\/[0-9a-f-]+$/.test(new URL(request.url()).pathname));
  await attach.click();
  expect(new URL((await retriedAttach).url()).pathname).toBe(failedPath);
  await expect(assigned).toHaveCount(1);
  await expect(assigned.locator("span")).toHaveText(["主题：Simulink"]);
  await expect(status).toHaveText("分类已关联到笔记。");

  await kind.selectOption("tag");
  await name.fill("电力电子");
  await create.click();
  await expect(status).toContainText("分类已保存到空间");
  const tag = await classification.getByLabel("已有主题或标签", { exact: true }).inputValue();
  await attach.click();
  await expect(assigned).toHaveCount(2);
  await expect(assigned.locator("span")).toHaveText(["标签：电力电子", "主题：Simulink"]);
  await expect(status).toHaveText("分类已关联到笔记。");
  // Matching type+normalized name and repeated PUT must reuse saved rows.
  await kind.selectOption("topic");
  await name.fill(" simULink ");
  await create.click();
  await expect(status).toContainText("该分类已关联到本笔记");
  expect((await page.request.put(`${root}/notes/${fixtureNote}/labels/${topic}`, { headers })).ok()).toBe(true);
  const labels = await page.request.get(`${root}/labels?cursor=invalid&limit=0`, { headers });
  expect(labels.ok()).toBe(true);
  expect((await labels.json()).data).toHaveLength(2);
  await expect(versions.locator("option")).toHaveCount(beforeVersions);
  await expect(content.locator("pre")).toHaveText(beforeMarkdown ?? "");
  expect((await page.request.get(`${root}/notes?label_id=invalid`, { headers })).status()).toBe(422);
  expect((await page.request.get(`${root}/notes/${fixtureNote}/labels?label_id=invalid`, { headers })).ok()).toBe(true);

  await knowledge.getByLabel("笔记主题或标签", { exact: true }).selectOption(topic);
  const filtered = page.waitForRequest(request => request.method() === "GET" && /\/notes$/.test(new URL(request.url()).pathname));
  await knowledge.getByRole("button", { name: "应用笔记筛选", exact: true }).click();
  expect(new URL((await filtered).url()).searchParams.get("label_id")).toBe(topic);
  await expect(notes).toHaveCount(1);
  await expect(knowledge.getByLabel("当前笔记筛选", { exact: true })).toContainText("Simulink");
  const historical = await versions.locator("option").last().getAttribute("value");
  if (!historical || historical === latestRevision) throw new Error("Missing historical protocol revision");
  await versions.selectOption(historical);
  await expect(versions).toHaveValue(historical);
  await expect(assigned).toHaveCount(2);
  await knowledge.getByRole("button", { name: "打开最新版本", exact: true }).click();
  await knowledge.getByRole("button", { name: "开始人工修订", exact: true }).click();
  const editor = knowledge.getByRole("region", { name: "笔记人工修订", exact: true });
  await editor.getByLabel("修订标题", { exact: true }).fill("人工分类保留验收（协议内容，无模型调用）");
  await expect(knowledge.getByLabel("笔记主题或标签", { exact: true })).toBeDisabled();
  await expect(name).toBeDisabled();
  await expect(classification.getByRole("button", { name: "移除主题：Simulink", exact: true })).toBeDisabled();
  await editor.getByRole("button", { name: "保存为新版本", exact: true }).click();
  await expect(editor).not.toBeVisible();
  await expect(content).toContainText("人工分类保留验收");
  await expect(assigned).toHaveCount(2);
  await expect(notes).toHaveCount(1);
  await expect(versions.locator("option")).toHaveCount(beforeVersions + 1);

  // Removing the active filter's association updates the list and retains detail.
  await classification.getByRole("button", { name: "移除主题：Simulink", exact: true }).click();
  await expect(assigned).toHaveCount(1);
  await expect(notes).toHaveCount(0);
  await expect(content).toContainText("人工分类保留验收");
  await expect(knowledge.getByRole("status", { name: "笔记列表状态", exact: true })).toContainText("详情仍保留");
  expect((await page.request.delete(`${root}/notes/${fixtureNote}/labels/${topic}`, { headers })).ok()).toBe(true);
  await classification.getByRole("button", { name: "刷新笔记分类", exact: true }).click();
  await expect(status).toHaveText("已加载真实笔记分类。");
  await expect(assigned).toHaveCount(1);
  await knowledge.getByRole("button", { name: "重置笔记筛选", exact: true }).click();
  await expect(notes).toHaveCount(1);
  await expect(knowledge.getByLabel("笔记主题或标签", { exact: true })).toHaveValue("");
  await knowledge.getByLabel("笔记主题或标签", { exact: true }).selectOption(tag);
  await knowledge.getByRole("button", { name: "应用笔记筛选", exact: true }).click();
  await expect(notes).toHaveCount(1);

  await page.locator('.account-module-nav a[href="#audit"]').click();
  const audit = page.getByRole("region", { name: "空间审计记录", exact: true });
  await audit.getByRole("button", { name: "刷新审计记录", exact: true }).click();
  await expect(audit.getByRole("status")).toHaveText("已加载真实审计记录。");
  await expect(audit.getByRole("listitem").filter({ hasText: "创建主题或标签" })).toHaveCount(2);
  await expect(audit.getByRole("listitem").filter({ hasText: "关联笔记分类" })).toHaveCount(2);
  await expect(audit.getByRole("listitem").filter({ hasText: "移除笔记分类关联" })).toHaveCount(1);
  await expect(audit).not.toContainText("organization.label_");
  // Refresh reconciles a selected option after another member attaches it.
  await page.locator('.account-module-nav a[href="#knowledge"]').click();
  const available = classification.getByLabel("已有主题或标签", { exact: true });
  await available.selectOption(topic);
  expect((await page.request.put(`${root}/notes/${fixtureNote}/labels/${topic}`, { headers })).ok()).toBe(true);
  await classification.getByRole("button", { name: "刷新笔记分类", exact: true }).click();
  await expect(status).toHaveText("已加载真实笔记分类。");
  await expect(assigned).toHaveCount(2);
  await expect(available).toHaveValue("");
  await expect(attach).toBeDisabled();
  await page.locator('.account-module-nav a[href="#knowledge"]').click();
  const manager = knowledge.getByRole("region", { name: "分类目录维护", exact: true });
  const directoryStatus = manager.getByRole("status");
  const refreshDirectory = manager.getByRole("button", { name: "刷新分类目录", exact: true });
  const choose = manager.getByRole("combobox", { name: "选择维护分类", exact: true });
  const saveDirectory = manager.getByRole("button", { name: "保存分类维护", exact: true });
  await refreshDirectory.click();
  await expect(directoryStatus).toHaveText("已加载可维护的分类目录。");
  await choose.selectOption(topic);
  await manager.getByLabel("维护后的分类名称", { exact: true }).fill("Simulink维护后");
  await manager.getByLabel("确认更新这个共享分类，已有笔记关联保留", { exact: true }).check();
  await saveDirectory.click();
  await expect(directoryStatus).toContainText("分类维护已保存");
  await expect(assigned.locator("span")).toContainText(["标签：电力电子", "主题：Simulink维护后"]);
  await refreshDirectory.click();
  await expect(directoryStatus).toHaveText("已加载可维护的分类目录。");
  await choose.selectOption(topic);
  await manager.getByLabel("允许新的笔记关联（取消为归档）", { exact: true }).uncheck();
  await manager.getByLabel("确认更新这个共享分类，已有笔记关联保留", { exact: true }).check();
  await saveDirectory.click();
  await expect(directoryStatus).toContainText("分类维护已保存");
  await expect(assigned.locator("span")).toContainText(["标签：电力电子", "主题：Simulink维护后（已归档）"]);
  await refreshDirectory.click();
  await expect(directoryStatus).toHaveText("已加载可维护的分类目录。");
  await choose.selectOption(topic);
  await manager.getByLabel("允许新的笔记关联（取消为归档）", { exact: true }).check();
  await manager.getByLabel("确认更新这个共享分类，已有笔记关联保留", { exact: true }).check();
  await saveDirectory.click();
  await expect(directoryStatus).toContainText("分类维护已保存");
  await refreshDirectory.click();
  await expect(directoryStatus).toHaveText("已加载可维护的分类目录。");
  // A stale directory is never blindly replayed after an unknown transport result.
  await choose.selectOption(topic);
  await manager.getByLabel("维护后的分类名称", { exact: true }).fill("断网不能确认");
  await manager.getByLabel("确认更新这个共享分类，已有笔记关联保留", { exact: true }).check();
  await page.context().setOffline(true);
  await saveDirectory.click();
  await expect(directoryStatus).toContainText("保存结果可能未知");
  await expect(choose).not.toBeVisible();
  await page.context().setOffline(false);
  await refreshDirectory.click();
  await expect(directoryStatus).toHaveText("已加载可维护的分类目录。");
  await expect(manager.getByRole("list", { name: "可维护分类" })).toContainText("Simulink维护后 · 启用");
  await manager.screenshot({ path: ".cache/module-results/label-management-protocol.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await manager.screenshot({ path: ".cache/module-results/label-management-mobile-protocol.png" });
  expect(paidPosts).toBe(0);
  expect(collectionPosts).toBe(0);
});
