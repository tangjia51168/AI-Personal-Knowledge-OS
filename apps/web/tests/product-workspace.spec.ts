  await answer.getByRole("button", { name: "读取个人问答记录", exact: true }).click();
  await expect(answer.getByRole("status", { name: "证据问答状态" })).toContainText("最近 1 条个人问答记录");
  await answer.getByRole("button", { name: "打开问答记录", exact: true }).click();
  await answer.screenshot({ path: ".cache/module-results/v1-research-history.png" });

  await nav.locator('a[href="#jobs"]').click();
  const schedules = page.getByRole("region", { name: "公开来源定时同步", exact: true });
