  await expect(schedules.getByRole("status", { name: "同步计划状态" })).toContainText("已保存同步计划");
  await schedules.getByRole("button", { name: "暂停此同步计划", exact: true }).click();
  await expect(schedules).toContainText("已暂停 · 每 1440 分钟 · 版本 2");
