"""Verify the actual API/Worker/Beat storage identities on the local acceptance stack.

Docker inspection and subprocess output stay in memory. Reports contain only
booleans and exception class names, never environment values or command output.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path
from uuid import uuid4

import boto3
from botocore.config import Config

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts import operations_check  # noqa: E402

SERVICES = ("api", "worker", "beat")
REPORT_ROOT = ROOT / ".cache/storage-runtime"


def verify_environment(item: dict, service: str, values: dict[str, str]) -> None:
    """Reject operator credentials even when accidentally assigned another name."""
    labels = item.get("Config", {}).get("Labels", {})
    if (
        labels.get("com.docker.compose.project") != operations_check.PROJECT
        or labels.get("com.docker.compose.service") != service
        or not item.get("State", {}).get("Running")
    ):
        raise RuntimeError("Runtime container identity is invalid")
    environment = dict(
        entry.split("=", 1) for entry in item.get("Config", {}).get("Env", []) if "=" in entry
    )
    if any(
        name in environment
        for name in ("MINIO_ROOT_USER", "MINIO_ROOT_PASSWORD", "MIGRATION_DATABASE_URL")
    ):
        raise RuntimeError("Runtime container holds operator configuration")
    operator_values = (values["S3_ACCESS_KEY"], values["S3_SECRET_KEY"])
    if any(
        secret and secret in value for secret in operator_values for value in environment.values()
    ):
        raise RuntimeError("Runtime container holds storage operator credentials")
    if (
        not environment.get("S3_ACCESS_KEY")
        or not environment.get("S3_SECRET_KEY")
        or environment.get("S3_SESSION_TOKEN")
        or environment.get("S3_BUCKET") != values["S3_BUCKET"]
        or environment.get("S3_ENDPOINT_URL") != "http://minio:9000"
    ):
        raise RuntimeError("Runtime storage configuration is invalid")


def probe_source(outside_key: str, other_bucket: str) -> str:
    # Values are generated by this operator drill, never a user-supplied URL/key.
    return f"""
import json
from uuid import uuid4
from app.core.config import get_settings
from app.integrations.storage import get_s3_client, tenant_object_key
from botocore.exceptions import ClientError

def denied(operation):
    try:
        response = operation()
    except ClientError as error:
        if error.response["ResponseMetadata"]["HTTPStatusCode"] == 403:
            return
        raise RuntimeError("Expected authorization denial") from None
    if response and "Body" in response:
        response["Body"].close()
    raise RuntimeError("Unexpected storage permission")

client = get_s3_client()
bucket = get_settings().s3_bucket
key = tenant_object_key(uuid4(), uuid4())
checks = {{}}
try:
    client.head_bucket(Bucket=bucket)
    client.put_object(Bucket=bucket, Key=key, Body=b"runtime-identity-acceptance")
    response = client.get_object(Bucket=bucket, Key=key)
    try:
        if response["Body"].read() != b"runtime-identity-acceptance":
            raise RuntimeError("Object bytes differed")
    finally:
        response["Body"].close()
    checks["application_head_put_get_delete"] = True
    denied(lambda: client.get_bucket_policy(Bucket=bucket))
    checks["bucket_policy_denied"] = True
    denied(lambda: client.get_object(Bucket=bucket, Key={outside_key!r}))
    checks["outside_prefix_read_denied"] = True
    denied(lambda: client.put_object(Bucket=bucket, Key={outside_key!r}, Body=b"rejected"))
    checks["outside_prefix_write_denied"] = True
    denied(lambda: client.head_bucket(Bucket={other_bucket!r}))
    checks["other_bucket_denied"] = True
    try:
        listed = client.list_buckets().get("Buckets", [])
        if len(listed) > 1 or any(item["Name"] != bucket for item in listed):
            raise RuntimeError("Unrelated bucket listed")
    except ClientError as error:
        if error.response["ResponseMetadata"]["HTTPStatusCode"] != 403:
            raise RuntimeError("Unexpected enumeration failure") from None
    checks["bucket_enumeration_limited_or_denied"] = True
except Exception as error:
    checks["failure"] = type(error).__name__
finally:
    try:
        client.delete_object(Bucket=bucket, Key=key)
    except Exception as error:
        checks["cleanup_failure"] = type(error).__name__
    client.close()
print(json.dumps(checks))
"""


def check_process(service: str, outside_key: str, other_bucket: str) -> dict:
    result = subprocess.run(
        [
            operations_check.docker_path(),
            "exec",
            "-i",
            f"{operations_check.PROJECT}-{service}-1",
            "python",
            "-",
        ],
        input=probe_source(outside_key, other_bucket).encode(),
        capture_output=True,
        timeout=65,
        check=False,
    )
    if result.returncode or len(result.stdout) > 4096:
        raise RuntimeError("Runtime storage probe failed")
    payload = json.loads(result.stdout)
    expected = {
        "application_head_put_get_delete",
        "bucket_policy_denied",
        "outside_prefix_read_denied",
        "outside_prefix_write_denied",
        "other_bucket_denied",
        "bucket_enumeration_limited_or_denied",
    }
    if set(payload) != expected or any(value is not True for value in payload.values()):
        raise RuntimeError("Runtime storage permissions failed")
    return payload


def run_acceptance() -> Path:
    values = operations_check.load_acceptance()
    operations_check.check_containers(values)
    directory = REPORT_ROOT / uuid4().hex
    directory.mkdir(parents=True, exist_ok=False)
    checks: dict = {}
    client = boto3.client(
        "s3",
        endpoint_url=values["S3_ENDPOINT_URL"],
        aws_access_key_id=values["S3_ACCESS_KEY"],
        aws_secret_access_key=values["S3_SECRET_KEY"],
        region_name=values.get("S3_REGION", "us-east-1"),
        config=Config(
            connect_timeout=3,
            read_timeout=5,
            retries={"max_attempts": 0},
            proxies={},
            s3={"addressing_style": "path"},
        ),
    )
    outside = "acceptance-runtime/" + uuid4().hex
    other_bucket = "outside-" + uuid4().hex
    try:
        # A known existing out-of-prefix object proves denial rather than absence.
        client.put_object(Bucket=values["S3_BUCKET"], Key=outside, Body=b"operator-canary")
        for service in SERVICES:
            raw = operations_check.run_docker("inspect", f"{operations_check.PROJECT}-{service}-1")
            items = json.loads(raw)
            if len(items) != 1:
                raise RuntimeError("Unexpected runtime container inspection")
            verify_environment(items[0], service, values)
            checks[service] = {
                "operator_credentials_absent": True,
                **check_process(service, outside, other_bucket),
            }
    except Exception as error:
        checks["failure"] = type(error).__name__
    finally:
        try:
            client.delete_object(Bucket=values["S3_BUCKET"], Key=outside)
        except Exception as error:
            checks["cleanup_failure"] = type(error).__name__
        client.close()
    passed = set(checks) == set(SERVICES)
    report = {
        "status": "passed" if passed else "failed",
        "completed_at": datetime.now(UTC).isoformat(),
        "checks": checks,
        "local_runtime_replaced": passed,
        "production_runtime_replaced": False,
    }
    path = directory / "summary.json"
    path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    if not passed:
        raise RuntimeError("Runtime storage identity acceptance failed; see sanitized report")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--acceptance", action="store_true", required=True)
    parser.parse_args()
    try:
        path = run_acceptance()
    except Exception as error:
        raise SystemExit(f"Runtime storage check failed ({type(error).__name__})") from None
    print(f"PASS: actual API/Worker/Beat scoped storage; report: {path}")


if __name__ == "__main__":
    main()
